"""Generate host/container manifests without changing the original course checker."""
import argparse
import os
from pathlib import Path
from urllib.parse import quote

import yaml

ROOT = Path(__file__).resolve().parents[2]
SERVICES = ("crm", "catalog", "pos", "wms")


def dsn(user, host, port, service):
    key = {"postgres": "POSTGRES_PASSWORD", "app": "APP_PASSWORD", "checker": "CHECKER_PASSWORD"}[user]
    password = quote(os.environ.get(key, user), safe="")
    return f"postgresql://{user}:{password}@{host}:{port}/{service}_service_db"


def manifest(container=False):
    result = yaml.safe_load((ROOT / "hw01_submission.dev.yaml").read_text())
    rw, ro, admin = (("pgbouncer-rw", 6432), ("pgbouncer-ro", 6432), ("haproxy", 5000)) if container else (
        ("localhost", 6432), ("localhost", 6433), ("localhost", 5000))
    result["connections"] = {
        role: {service: dsn(user, host, port, service) for service in SERVICES}
        for role, user, (host, port) in (
            ("master", "checker", rw), ("replica", "checker", ro),
            ("writer", "app", rw), ("admin", "postgres", admin))
    }
    result["ha"] = {
        "mode": "patroni",
        "pooler_dsn": dsn("checker", *rw, "pos"),
        "haproxy_rw_dsn": dsn("checker", "haproxy" if container else "localhost", 5000, "pos"),
        "haproxy_ro_dsn": dsn("checker", "haproxy" if container else "localhost", 5001, "pos"),
        "patroni_api": "http://postgres1:8008" if container else "http://localhost:8008",
        "expected_members": 3,
        "journal": "docs/failover_journal.md",
    }
    result["entrypoint"] = {
        "up": "docker compose up -d --build",
        "wait_ready": "./scripts/wait_ready.sh",
        "seed": "./scripts/seed.sh --seed 42",
        "seed_delta": "./scripts/seed_delta.sh",
        "down": "docker compose down",
    }
    if container:
        # The checker only executes seed_delta. No nested Docker socket is needed.
        result["entrypoint"].update({
            "wait_ready": "python scripts/infra/wait_ready.py",
            "seed": "python scripts/infra/seed.py --seed 42",
            "seed_delta": "python scripts/infra/seed_delta.py",
        })
    return result


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--output-dir", type=Path, default=ROOT)
    args = parser.parse_args()
    args.output_dir.mkdir(parents=True, exist_ok=True)
    for container in (False, True):
        filename = "hw01_submission.container.yaml" if container else "hw01_submission.yaml"
        path = args.output_dir / filename
        path.write_text("# Generated by scripts/infra/submission.py; default local credentials.\n" +
                        yaml.safe_dump(manifest(container), allow_unicode=True, sort_keys=False), encoding="utf-8")
        print(f"wrote {path.name}")


if __name__ == "__main__":
    main()
